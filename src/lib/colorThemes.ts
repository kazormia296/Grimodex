export interface ThemePalette {
  "--background": string;
  "--foreground": string;
  "--card": string;
  "--card-foreground": string;
  "--popover": string;
  "--popover-foreground": string;
  "--primary": string;
  "--primary-foreground": string;
  "--secondary": string;
  "--secondary-foreground": string;
  "--muted": string;
  "--muted-foreground": string;
  "--accent": string;
  "--accent-foreground": string;
  "--destructive": string;
  "--destructive-foreground": string;
  "--border": string;
  "--input": string;
  "--ring": string;
  "--sidebar-background": string;
  "--sidebar-foreground": string;
  "--sidebar-primary": string;
  "--sidebar-primary-foreground": string;
  "--sidebar-accent": string;
  "--sidebar-accent-foreground": string;
  "--sidebar-border": string;
  "--sidebar-ring": string;
  "--content-background": string;
  "--content-foreground": string;
  "--content-foreground-secondary": string;
  "--content-foreground-muted": string;
  "--content-accent": string;
  "--content-border": string;
  // Ambient background highlight tints (top-left / top-right radial).
  // Decoupled from --primary / --content-accent so themes can tune the
  // Zen background independently from the brand colours.
  "--ambient-tint-a": string;
  "--ambient-tint-b": string;
  // Attribution highlight hues (human / ai / unknown). The HUE is constant
  // across every theme (human=blue 220°, ai=teal 165°, unknown=amber 30°) for a
  // consistent colour language; only lightness/chroma are tuned per theme×mode
  // so the color-mix highlight stays legible on each --content-background
  // (dark themes use brighter, higher-chroma values). See attributionColors.ts.
  "--attribution-human": string;
  "--attribution-ai": string;
  "--attribution-unknown": string;
}

export interface PaletteSlot {
  hl: string; // highlight background
  tx: string; // text color on highlight background
  fg: string; // text-only foreground color
  label: string;
}

export const PALETTE_SIZE = 10;

export interface ColorTheme {
  id: string;
  name: string;
  light: ThemePalette;
  dark: ThemePalette;
  palette: { light: PaletteSlot[]; dark: PaletteSlot[] };
}

