/**
 * MP-4b PR-0：legacy の read tool（M4 の 20 本）の特性試験が使う seed の定義（data だけ）。
 *
 * 何も import しない（`@/db/schema` にも依存しない）。後続の PR で実 addon の同値 spec や
 * electron 側の試験が同じ定義を再利用できるようにするため。表名と列名は SQLite の実名
 * （snake_case）、真偽は 0/1、foreshadow 系の時刻は epoch ms の整数、他は ISO 文字列。
 *
 * 構成（3 project）：
 * - `main`：全部入りの project。archived の場面・folder（外部ファイルの消失で archived）、
 *   hidden の Codex、secret の出来事・伏線を含む。
 * - `other`：main と同じ名前・タグ・題名を持つ別 project の行（XPROJ の漏れを見る）。
 * - `empty`：行が 1 つも無い project（「空」の結果を見る）。
 * - `big`：9 場面に結ばれた筋を 1 本だけ持つ project（`get_thread_scenes` の上限 8 を見る）。
 *
 * codex_types（character／location／item／lore）は projects の INSERT trigger が作る。
 * ここでは書かない。
 */

export type SeedValue = string | number | null;
export type SeedRow = Readonly<Record<string, SeedValue>>;
export interface SeedTable {
  readonly table: string;
  readonly rows: readonly SeedRow[];
}

