/** ProseMirror の doc（段落 1 つ以上）を JSON 文字列で返す。 */
export function pmDoc(...paragraphs: string[]): string {
  return JSON.stringify({
    type: "doc",
    content: paragraphs.map((text) => ({
      type: "paragraph",
      content: [{ type: "text", text }],
    })),
  });
}

