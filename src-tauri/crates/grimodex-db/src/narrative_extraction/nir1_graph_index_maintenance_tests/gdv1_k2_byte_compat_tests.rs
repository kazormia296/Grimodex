//! GDV/1 K-2 (b) byte compatibility (contract revision 6, section 8, "座標と byte 互換").
//!
//! What GDV/1 must not change is checked against values that the build BEFORE
//! GDV/1 (`origin/master` at the branch point, `79077a3d`) produced:
//!
//! * `tests/support/gdv1-k2-{none,current,chronicle}.db.gz` are databases that
//!   the pre-GDV/1 build made and then `VACUUM INTO`'d, each ending with a
//!   completed, clean Verify Run that the pre-GDV/1 build sealed (with its skip
//!   evidence and completion digest): a project with no Graph binding, a project
//!   with a current Graph binding, and a project that has a Chronicle binding
//!   only (no Graph binding). They are ordinary fixtures; they are never
//!   regenerated by this build.
//! * The `EXPECTED_*` constants were captured on the pre-GDV/1 build by running
//!   `observe_snapshot` (this file, unchanged) on each snapshot in a separate
//!   process, once per snapshot and reader, each on its own fresh unpacked copy
//!   (a reader may write). They are full values: the report's
//!   `serde_json::to_value` text, the completion digests, error messages in full,
//!   and the `Debug` text of the Repair plan, the readiness and the discovery
//!   results. Nothing is a prefix or a count.
//!
//! The snapshot is fixed, so every value is deterministic; the same file passes
//! on the pre-GDV/1 build and on this build. This file only uses APIs that exist
//! before GDV/1.

