const NONE_DB: &[u8] = include_bytes!("../../../tests/support/gdv1-k2-none.db.gz");
const CURRENT_DB: &[u8] = include_bytes!("../../../tests/support/gdv1-k2-current.db.gz");
const CHRONICLE_DB: &[u8] = include_bytes!("../../../tests/support/gdv1-k2-chronicle.db.gz");

/// Which snapshot, its database, and the project the pre-GDV/1 build sealed.
pub(super) struct Snapshot {
    pub name: &'static str,
    pub compressed: &'static [u8],
    pub project: &'static str,
}

pub(super) const SNAPSHOTS: [Snapshot; 3] = [
    Snapshot {
        name: "none",
        compressed: NONE_DB,
        project: PROJECT,
    },
    Snapshot {
        name: "current",
        compressed: CURRENT_DB,
        project: PROJECT,
    },
    Snapshot {
        name: "chronicle",
        compressed: CHRONICLE_DB,
        project: PROJECT,
    },
];

/// A fresh, private, unpacked copy of a snapshot.
pub(super) fn open_snapshot(snapshot: &Snapshot) -> Result<(TestDirectory, Database)> {
    let directory =
        TestDirectory(std::env::temp_dir().join(format!("gdv1-k2-{}", uuid::Uuid::new_v4())));
    std::fs::create_dir_all(&directory.0)?;
    let mut bytes = Vec::new();
    GzDecoder::new(snapshot.compressed).read_to_end(&mut bytes)?;
    let path = directory.0.join("grimodex.db");
    std::fs::write(&path, bytes)?;
    let db = Database::new(&path)?;
    Ok((directory, db))
}

fn text<T: std::fmt::Debug>(result: &Result<T>) -> String {
    match result {
        Ok(value) => format!("Ok({value:?})"),
        Err(error) => format!("Err({error:#})"),
    }
}

/// The newest completed Verify Run of the snapshot: (id, epoch, outcome JSON).
pub(super) fn latest_completed_verify(
    db: &Database,
    project: &str,
) -> Result<(String, String, String)> {
    db.with_conn(|conn| {
        Ok(conn.query_row(
            "SELECT id, semantic_epoch_id, outcome_summary_json
               FROM narrative_extraction_runs
              WHERE project_id = ?1 AND run_kind = 'dependency-verify' AND status = 'completed'
              ORDER BY rowid DESC LIMIT 1",
            [project],
            |row| Ok((row.get(0)?, row.get(1)?, row.get(2)?)),
        )?)
    })
}

fn verify_request(project: &str, epoch: &str) -> MaintenanceCycleRequest {
    MaintenanceCycleRequest {
        work: vec![MaintenanceWorkRequest {
            project_id: project.into(),
            run_kind: AutomaticRunKind::Verify,
            work_key: format!("dependency-verify:{epoch}"),
            semantic_epoch_id: Some(epoch.to_string()),
            reasons: vec!["workspace-opened".into()],
        }],
        wake_project_ids: Vec::new(),
        delivery_sequence: None,
        delivery_fingerprint: None,
        workspace_binding: None,
    }
}

fn run_count(db: &Database, project: &str) -> Result<i64> {
    db.with_conn(|conn| {
        Ok(conn.query_row(
            "SELECT COUNT(*) FROM narrative_extraction_runs WHERE project_id = ?1",
            [project],
            |row| row.get(0),
        )?)
    })
}

fn finding_count(db: &Database, project: &str) -> Result<i64> {
    db.with_conn(|conn| {
        Ok(conn.query_row(
            "SELECT COUNT(*) FROM narrative_maintenance_finding_lifecycle WHERE project_id = ?1",
            [project],
            |row| row.get(0),
        )?)
    })
}

/// One reader, on its own fresh copy: `(name, observed text)`.
type Reader = (&'static str, fn(&Database, &str) -> Result<String>);

fn read_report(db: &Database, project: &str) -> Result<String> {
    let report =
        db.with_conn_mut(|conn| rr::verify_narrative_dependency_graph_for_project(conn, project))?;
    Ok(serde_json::to_string(&serde_json::to_value(&report)?)?)
}

/// The stored report of the pre-GDV/1 Run must be the very text a fresh report
/// serializes to (key order included): the new build reads and writes the same
/// bytes.
fn read_stored_report_equals_fresh(db: &Database, project: &str) -> Result<String> {
    let (_, _, outcome) = latest_completed_verify(db, project)?;
    let stored: serde_json::Value = serde_json::from_str(&outcome)?;
    let fresh = read_report(db, project)?;
    Ok(format!(
        "stored={} fresh_equal={}",
        serde_json::to_string(&stored["report"])?,
        serde_json::to_string(&stored["report"])? == fresh
    ))
}

fn read_digest_uncontrolled(db: &Database, project: &str) -> Result<String> {
    let result = db.with_conn_mut(|conn| Ok(rr::durable_graph_state_digest(conn, project)))?;
    Ok(text(&result))
}

fn read_digest_foreground(db: &Database, project: &str) -> Result<String> {
    let result = db.with_conn_mut(|conn| {
        let mut tx = crate::scoped_tx::ScopedTransaction::begin(conn)?;
        let mut control = ForegroundValidationControl;
        let digest = rr::durable_graph_state_digest_with_control(&mut tx, project, &mut control);
        tx.rollback()?;
        Ok(digest)
    })?;
    Ok(text(&result))
}

fn read_main_discovery(db: &Database, project: &str) -> Result<String> {
    let coordinates = mr::effective_maintenance_coordinates(None)?;
    let result = mr::discover_maintenance_project_for_main(
        db,
        project,
        "workspace-opened",
        Some(&coordinates),
        None,
    );
    Ok(text(&result))
}

fn read_skip_uncontrolled(db: &Database, project: &str) -> Result<String> {
    let coordinates = mr::effective_maintenance_coordinates(None)?;
    let result = mr::discover_durable_maintenance_work_with_coordinates(
        db,
        project,
        "workspace-opened",
        Some(&coordinates),
    );
    Ok(text(&result))
}

/// The same decision through a cycle's own control (`MaintenanceCycleControl`,
/// the control a real cycle gives its discovery), not a stand-in.
fn read_skip_in_cycle_control(db: &Database, project: &str) -> Result<String> {
    let coordinates = mr::effective_maintenance_coordinates(None)?;
    let recorder = Recorder::default();
    let result = with_control(&recorder, |control| {
        mr::discover_durable_maintenance_work_with_coordinates_and_control(
            db,
            project,
            "workspace-opened",
            Some(&coordinates),
            control,
        )
    });
    Ok(text(&result))
}

fn read_repair_seal(db: &Database, project: &str) -> Result<String> {
    let (run_id, epoch, _) = latest_completed_verify(db, project)?;
    let result = db.with_conn_mut(|conn| {
        Ok(crate::narrative_extraction::repair::seal_repair_plan(
            conn, project, &run_id, &epoch,
        ))
    })?;
    Ok(text(&result))
}

fn read_c2z_readiness(db: &Database, project: &str) -> Result<String> {
    let result = db.with_conn_mut(|conn| {
        Ok(crate::narrative_extraction::inspect_project_cutover_readiness(conn, project))
    })?;
    Ok(text(&result))
}

/// A cycle that is handed the Verify item of the sealed Verify: the runtime's
/// skip decision under the cycle's own control. Run count and Findings before
/// and after show whether the sealed outcome was reused.
fn read_cycle_with_the_verify_item(db: &Database, project: &str) -> Result<String> {
    let (_, epoch, _) = latest_completed_verify(db, project)?;
    let runs_before = run_count(db, project)?;
    let findings_before = finding_count(db, project)?;
    let recorder = Recorder::default();
    let result = run_cycle_on(db, None, &verify_request(project, &epoch), None, &recorder);
    Ok(format!(
        "{} runs {}->{} findings {}->{}",
        text(&result.map(|result| result.status)),
        runs_before,
        run_count(db, project)?,
        findings_before,
        finding_count(db, project)?
    ))
}

pub(super) const READERS: [Reader; 9] = [
    ("report", read_report),
    ("stored report", read_stored_report_equals_fresh),
    ("digest uncontrolled", read_digest_uncontrolled),
    ("digest foreground", read_digest_foreground),
    ("main discovery", read_main_discovery),
    ("skip uncontrolled", read_skip_uncontrolled),
    ("skip in cycle control", read_skip_in_cycle_control),
    ("repair seal", read_repair_seal),
    ("c2z readiness", read_c2z_readiness),
];

/// Every reader on its own copy of the snapshot, then the cycle on one more.
pub(super) fn observe_snapshot(snapshot: &Snapshot) -> Result<Vec<String>> {
    let mut lines = Vec::new();
    for (name, reader) in READERS {
        let (_directory, db) = open_snapshot(snapshot)?;
        lines.push(format!("{name}: {}", reader(&db, snapshot.project)?));
    }
    let (_directory, db) = open_snapshot(snapshot)?;
    lines.push(format!(
        "cycle with the Verify item: {}",
        read_cycle_with_the_verify_item(&db, snapshot.project)?
    ));
    Ok(lines)
}

/// The report, the completion digests and the five readers give the same values
/// on a Verify outcome that the pre-GDV/1 build sealed, for a project with no
/// Graph binding, a current Graph binding, and a Chronicle binding only.
#[test]
fn a_pre_gdv1_sealed_outcome_reads_the_same_before_and_after() -> Result<()> {
    let _serial = serial();
    for (snapshot, expected) in
        SNAPSHOTS
            .iter()
            .zip([EXPECTED_NONE, EXPECTED_CURRENT, EXPECTED_CHRONICLE])
    {
        let lines = observe_snapshot(snapshot)?;
        if std::env::var_os("GDV1_K2_DUMP").is_some() {
            for line in &lines {
                eprintln!("GDV1_K2_LINE {} {line:?}", snapshot.name);
            }
            // Capture mode (only used to fill in `EXPECTED_*` on the pre-GDV/1 build).
            continue;
        }
        assert_eq!(lines.len(), expected.len(), "{}", snapshot.name);
        for (line, expected) in lines.iter().zip(expected) {
            assert_eq!(line, expected, "{}", snapshot.name);
        }
    }
    Ok(())
}

